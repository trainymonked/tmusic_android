internal fun createFavoriteTrackController(
    appState: TMusicAppMutableState,
    scope: CoroutineScope,
    musicRepository: RemoteMusicRepository,
    authRepository: RemoteAuthRepository,
    libraryCacheStore: LibraryCacheStore,
    canUseServerRequests: () -> Boolean,
    mergePlaylistPickerMetadata: (List<Playlist>) -> Unit,
    updateKnownTrackLikedState: (String, Boolean) -> Unit,
    updateTrackDownloadState: (String, DownloadState) -> Unit,
    ensureTrackDownloaded: suspend (Track) -> Unit,
    cacheDownloadedAssets: suspend (Track) -> Unit,
    refreshStorageStats: () -> Unit,
    loadArtwork: (String, ArtworkImageSize) -> Unit,
    enqueueLibraryMutation: (String, JSONObject) -> Unit,
    saveLibraryCache: () -> Unit,
    markServerUnavailable: (Throwable) -> Unit,
) = FavoriteTrackActionHost(
    scope = scope,
    canUseServerRequests = canUseServerRequests,
    getPlaylists = { appState.playlists },
    setPlaylists = { appState.playlists = it },
    getTracks = { appState.tracks },
    setTracks = { appState.tracks = it },
    getSavedAlbums = { appState.savedAlbums },
    musicRepository = musicRepository,
    authRepository = authRepository,
    libraryCacheStore = libraryCacheStore,
    setAccessToken = { appState.accessToken = it },
    mergePlaylistPickerMetadata = mergePlaylistPickerMetadata,
    updateKnownTrackLikedState = updateKnownTrackLikedState,
    updateTrackDownloadState = updateTrackDownloadState,
    ensureTrackDownloaded = ensureTrackDownloaded,
    cacheDownloadedAssets = cacheDownloadedAssets,
    refreshStorageStats = refreshStorageStats,
    getFavoriteSyncTrackIds = { appState.favoriteSyncTrackIds },
    setFavoriteSyncTrackIds = { appState.favoriteSyncTrackIds = it },
    loadArtwork = loadArtwork,
    enqueueLibraryMutation = enqueueLibraryMutation,
    saveLibraryCache = saveLibraryCache,
    markServerUnavailable = markServerUnavailable,
    setLibraryError = { appState.libraryError = it },
)

