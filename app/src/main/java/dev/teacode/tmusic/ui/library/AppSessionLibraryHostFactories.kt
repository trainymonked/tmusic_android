internal fun createAuthSessionActionHost(
    appState: TMusicAppMutableState,
    authRepository: RemoteAuthRepository,
    googleSignInTokenProvider: GoogleSignInTokenProvider,
    userPreferencesStore: UserPreferencesStore,
    libraryCacheStore: LibraryCacheStore,
    playbackStateStore: PlaybackStateStore,
    pendingPlayEventStore: PendingPlayEventStore,
    pendingLibraryMutationStore: PendingLibraryMutationStore,
    lastFmAuthTokenStore: LastFmAuthTokenStore,
    clearGaplessPlaybackState: () -> Unit,
) = AuthSessionActionHost(
    authRepository = authRepository,
    googleSignInTokenProvider = googleSignInTokenProvider,
    userPreferencesStore = userPreferencesStore,
    libraryCacheStore = libraryCacheStore,
    playbackStateStore = playbackStateStore,
    pendingPlayEventStore = pendingPlayEventStore,
    pendingLibraryMutationStore = pendingLibraryMutationStore,
    lastFmAuthTokenStore = lastFmAuthTokenStore,
    getLibraryLoadSerial = { appState.libraryLoadSerial },
    setLibraryLoadSerial = { appState.libraryLoadSerial = it },
    getLibraryLoadJob = { appState.libraryLoadJob },
    setLibraryLoadJob = { appState.libraryLoadJob = it },
    setAccount = { appState.account = it },
    setAccessToken = { appState.accessToken = it },
    setCanContinueOffline = { appState.canContinueOffline = it },
    setOfflineOnly = { appState.offlineOnly = it },
    setSyncMode = { appState.syncMode = it },
    setLibraryLoading = { appState.libraryLoading = it },
    setLibraryError = { appState.libraryError = it },
    setLibraryNotice = { appState.libraryNotice = it },
    setPlaylists = { appState.playlists = it },
    setTracks = { appState.tracks = it },
    setArtists = {
        appState.artists = it
        appState.artistServerSortOption = null
        appState.artistListCache = emptyMap()
    },
    setAlbums = { appState.albums = it },
    setSavedAlbums = { appState.savedAlbums = it },
    setRecentAlbums = { appState.recentAlbums = it },
    setDatabaseTrackCount = { appState.databaseTrackCount = it },
    setAlbumsByArtist = { appState.albumsByArtist = it },
    setAppearsOnByArtist = { appState.appearsOnByArtist = it },
    setLooseTracksByArtist = { appState.looseTracksByArtist = it },
    setSimilarArtistsByArtist = { appState.similarArtistsByArtist = it },
    resetLibraryPaging = {
        appState.libraryPaging = appState.libraryPaging.copy(
            artistNextOffset = 0,
            albumNextOffset = 0,
            artistHasMore = true,
            albumHasMore = true,
        )
    },
    setRecentAlbumsPaging = { appState.recentAlbumsPaging = it },
    setAlbumTrackHasMoreById = { appState.albumTrackHasMoreById = it },
    setPlaylistTrackHasMoreById = { appState.playlistTrackHasMoreById = it },
    setAlbumTracksById = { appState.albumTracksById = it },
    setSearchResults = { appState.searchResults = it },
    setPlayerState = { appState.playerState = it },
    setPlaybackQueue = { appState.playbackQueue = it },
    clearGaplessPlaybackState = clearGaplessPlaybackState,
    clearCrossfadeState = {
        appState.crossfadeJob?.cancel()
        appState.crossfadeJob = null
        appState.preparedCrossfade = null
    },
    setActivePlayEvent = { appState.activePlayEventState.value = it },
    setPendingPlayEventCount = { appState.pendingPlayEventCount = it },
    setPendingPlayEventSyncProgress = { appState.pendingPlayEventSyncProgress = it },
    setPendingLibraryMutationCount = { appState.pendingLibraryMutationCount = it },
    setPendingLastFmToken = { appState.pendingLastFmToken = it },
    setWaitingForLastFmSession = { appState.waitingForLastFmSession = it },
    setLastFmConnection = { appState.lastFmConnection = it },
    setScrobblingPaused = { appState.scrobblingPaused = it },
    setShuffleEnabled = { appState.shuffleEnabled = it },
    setRepeatMode = { appState.repeatMode = it },
    setProfileAvatarBitmap = { appState.profileAvatarBitmap = it },
    setProfileAvatarLoadKey = { appState.profileAvatarLoadKey = it },
    setPrefetchedPlaybackUrls = { appState.prefetchedPlaybackUrls = it },
    setPlaybackUrlPrefetchesInProgress = { appState.playbackUrlPrefetchesInProgress = it },
    setTrackForPlaylistAdd = { appState.trackForPlaylistAdd = it },
    setPlaylistPickerPlaylists = { appState.playlistPickerPlaylists = it },
    setPlaylistPickerLoading = { appState.playlistPickerLoading = it },
    setPlaylistMetadataLoaded = { appState.playlistMetadataLoaded = it },
    setDuplicatePlaylistForAdd = { appState.duplicatePlaylistForAdd = it },
    setPlaylistAddInProgress = { appState.playlistAddInProgress = it },
    setFullPlayerOpen = { appState.fullPlayerOpen = it },
    setQueueOpen = { appState.queueOpen = it },
    setDestination = { appState.destination = it },
    setBackStack = { appState.backStack = it },
    setAuthError = { appState.authError = it },
)

